// genru converts a RIPE NCC "delegated-ripencc-latest" statistics file into a
// plain list of CIDR prefixes allocated to a country (default RU).
//
//	go run ./tools/genru -in delegated-ripencc-latest -out ru_cidr.txt
package main

import (
	"bufio"
	"flag"
	"fmt"
	"math/bits"
	"net/netip"
	"os"
	"sort"
	"strconv"
	"strings"
)

func main() {
	in := flag.String("in", "", "delegated-ripencc-latest file")
	out := flag.String("out", "ru_cidr.txt", "output file")
	cc := flag.String("cc", "RU", "country code")
	flag.Parse()

	f, err := os.Open(*in)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer f.Close()

	var prefixes []netip.Prefix
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		p := strings.Split(sc.Text(), "|")
		if len(p) < 7 || p[1] != *cc || (p[6] != "allocated" && p[6] != "assigned") {
			continue
		}
		switch p[2] {
		case "ipv4":
			start, err := netip.ParseAddr(p[3])
			if err != nil {
				continue
			}
			n, err := strconv.ParseUint(p[4], 10, 64)
			if err != nil || n == 0 {
				continue
			}
			a := start.As4()
			cur := uint64(a[0])<<24 | uint64(a[1])<<16 | uint64(a[2])<<8 | uint64(a[3])
			for n > 0 {
				// largest block aligned at cur that fits in n
				size := uint64(1) << bits.TrailingZeros64(cur|1<<32)
				for size > n {
					size >>= 1
				}
				bitsLen := 32 - bits.TrailingZeros64(size)
				addr := netip.AddrFrom4([4]byte{byte(cur >> 24), byte(cur >> 16), byte(cur >> 8), byte(cur)})
				prefixes = append(prefixes, netip.PrefixFrom(addr, bitsLen))
				cur += size
				n -= size
			}
		case "ipv6":
			start, err := netip.ParseAddr(p[3])
			if err != nil {
				continue
			}
			l, err := strconv.Atoi(p[4])
			if err != nil || l < 1 || l > 128 {
				continue
			}
			prefixes = append(prefixes, netip.PrefixFrom(start, l))
		}
	}
	sort.Slice(prefixes, func(i, j int) bool {
		a, b := prefixes[i].Addr(), prefixes[j].Addr()
		if c := a.Compare(b); c != 0 {
			return c < 0
		}
		return prefixes[i].Bits() < prefixes[j].Bits()
	})
	o, err := os.Create(*out)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer o.Close()
	w := bufio.NewWriter(o)
	defer w.Flush()
	fmt.Fprintf(w, "# %s prefixes from RIPE NCC delegated statistics (generated by tools/genru)\n", *cc)
	for _, p := range prefixes {
		fmt.Fprintln(w, p.String())
	}
	fmt.Fprintf(os.Stderr, "%d prefixes written\n", len(prefixes))
}
